//! HS256 authentication with libcrux's HACL*-origin HMAC-SHA-256.
//!
//! Keys are instance-local, opaque handles. Both MAC generation and verification
//! use the shared secret inside this component; a verifier can also mint tokens.
//! Imported/stored key buffers are zeroized, but libcrux's internal temporaries
//! are not guaranteed wiped. The upstream primitive proofs do not cover this
//! wrapper, tag comparison, compilation to Wasm, or runtime side channels.
use std::sync::Mutex;
use subtle::ConstantTimeEq;
use zeroize::Zeroizing;

wit_bindgen::generate!({ world: "signing", path: "../wit" });
use exports::authentikate::crypto::hmac::{Error, Guest};

struct Component;
const MAX_KEYS: usize = 1024;
const KEY_LENGTH: usize = 32;
const TAG_LENGTH: usize = 32;
type SigningKey = Zeroizing<[u8; KEY_LENGTH]>;

struct KeyStore {
    keys: Vec<SigningKey>,
}
impl KeyStore {
    fn insert(&mut self, key: SigningKey) -> Result<u32, Error> {
        if self.keys.len() >= MAX_KEYS {
            return Err(Error::KeyStoreFull);
        }
        self.keys.push(key);
        Ok(self.keys.len() as u32)
    }
    fn get(&self, handle: u32) -> Result<&SigningKey, Error> {
        let index = handle.checked_sub(1).ok_or(Error::InvalidKey)?;
        self.keys.get(index as usize).ok_or(Error::InvalidKey)
    }
}
static KEYS: Mutex<KeyStore> = Mutex::new(KeyStore { keys: Vec::new() });

fn signing_key(bytes: &[u8]) -> Result<SigningKey, Error> {
    let bytes: &[u8; KEY_LENGTH] = bytes.try_into().map_err(|_| {
        Error::InvalidSecretKey(format!(
            "HS256 key must be {KEY_LENGTH} bytes, got {}",
            bytes.len()
        ))
    })?;
    let mut key = Zeroizing::new([0; KEY_LENGTH]);
    key.copy_from_slice(bytes);
    Ok(key)
}

fn mac(key: &[u8], message: &[u8]) -> Result<[u8; TAG_LENGTH], Error> {
    // Libcrux's one-shot API panics on lengths wider than u32. On wasm32 a
    // slice cannot exceed that bound, but native callers still get an error.
    if u32::try_from(key.len()).is_err() || u32::try_from(message.len()).is_err() {
        return Err(Error::InvalidTag("input exceeds u32 length limit".into()));
    }
    let mut tag = [0; TAG_LENGTH];
    libcrux_hmac::hmac_sha2_256(&mut tag, key, message);
    Ok(tag)
}

impl Guest for Component {
    fn import_key(secret_key: Vec<u8>) -> Result<u32, Error> {
        let secret_key = Zeroizing::new(secret_key);
        let key = signing_key(&secret_key)?;
        KEYS.lock()
            .map_err(|_| Error::KeyStoreUnavailable)?
            .insert(key)
    }
    fn sign(key: u32, message: Vec<u8>) -> Result<Vec<u8>, Error> {
        let keys = KEYS.lock().map_err(|_| Error::KeyStoreUnavailable)?;
        mac(keys.get(key)?.as_slice(), &message).map(|tag| tag.to_vec())
    }
    fn verify(key: u32, message: Vec<u8>, tag: Vec<u8>) -> Result<bool, Error> {
        let keys = KEYS.lock().map_err(|_| Error::KeyStoreUnavailable)?;
        let key = keys.get(key)?;
        let tag: &[u8; TAG_LENGTH] = tag.as_slice().try_into().map_err(|_| {
            Error::InvalidTag(format!(
                "HS256 tag must be {TAG_LENGTH} bytes, got {}",
                tag.len()
            ))
        })?;
        Ok(bool::from(mac(key.as_slice(), &message)?.ct_eq(tag)))
    }
}
export!(Component);

#[cfg(test)]
mod tests {
    use super::*;
    fn hex(s: &str) -> Vec<u8> {
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect()
    }
    #[test]
    fn rfc4231_vectors() {
        // Primitive vectors include short/long keys; the component deliberately
        // accepts only the 32-byte keys generated by this application's host.
        for (key, message, expected) in [
            (
                vec![0x0b; 20],
                b"Hi There".as_slice(),
                "b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7",
            ),
            (
                b"Jefe".to_vec(),
                b"what do ya want for nothing?".as_slice(),
                "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843",
            ),
            (
                vec![0xaa; 131],
                b"Test Using Larger Than Block-Size Key - Hash Key First".as_slice(),
                "60e431591ee0b67f0d8a26aacbf5b77f8e0bc6213728c5140546040f0ee37f54",
            ),
        ] {
            assert_eq!(mac(&key, message).unwrap().to_vec(), hex(expected));
        }
    }
    #[test]
    fn same_handle_signs_and_verifies() {
        let key = Component::import_key(vec![0x42; KEY_LENGTH]).unwrap();
        for message in [vec![], b"header.payload".to_vec(), vec![0, 128, 255]] {
            let tag = Component::sign(key, message.clone()).unwrap();
            assert_eq!(tag.len(), TAG_LENGTH);
            assert_eq!(tag, Component::sign(key, message.clone()).unwrap());
            assert!(Component::verify(key, message, tag).unwrap());
        }
    }
    #[test]
    fn rejects_wrong_key_message_and_every_tampered_tag_byte() {
        let key = Component::import_key(vec![1; KEY_LENGTH]).unwrap();
        let other = Component::import_key(vec![2; KEY_LENGTH]).unwrap();
        let tag = Component::sign(key, b"message".to_vec()).unwrap();
        assert!(!Component::verify(other, b"message".to_vec(), tag.clone()).unwrap());
        assert!(!Component::verify(key, b"different".to_vec(), tag.clone()).unwrap());
        for i in 0..TAG_LENGTH {
            let mut bad = tag.clone();
            bad[i] ^= 1;
            assert!(!Component::verify(key, b"message".to_vec(), bad).unwrap());
        }
    }
    #[test]
    fn lengths_and_handles_are_checked() {
        for length in [0, 16, 31, 33, 64] {
            assert!(matches!(
                Component::import_key(vec![0; length]),
                Err(Error::InvalidSecretKey(_))
            ));
        }
        let key = Component::import_key(vec![0; KEY_LENGTH]).unwrap();
        for length in [0, 16, 31, 33, 64] {
            assert!(matches!(
                Component::verify(key, vec![], vec![0; length]),
                Err(Error::InvalidTag(_))
            ));
        }
        for key in [0, MAX_KEYS as u32 + 1, u32::MAX] {
            assert!(matches!(
                Component::sign(key, vec![]),
                Err(Error::InvalidKey)
            ));
            assert!(matches!(
                Component::verify(key, vec![], vec![0; TAG_LENGTH]),
                Err(Error::InvalidKey)
            ));
        }
    }
    #[test]
    fn handles_are_bounded_and_not_reused() {
        let mut store = KeyStore { keys: Vec::new() };
        for expected in 1..=MAX_KEYS as u32 {
            assert_eq!(
                store
                    .insert(signing_key(&[7; KEY_LENGTH]).unwrap())
                    .unwrap(),
                expected
            );
        }
        assert!(matches!(
            store.insert(signing_key(&[8; KEY_LENGTH]).unwrap()),
            Err(Error::KeyStoreFull)
        ));
        assert_eq!(store.get(1).unwrap().as_slice(), &[7; KEY_LENGTH]);
        assert!(matches!(
            (KeyStore { keys: Vec::new() }).get(1),
            Err(Error::InvalidKey)
        ));
    }
}
